/* UI verification for the reconstruction, never for the Android application. */
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const root = path.resolve(__dirname, '..');
const base = process.env.SOULCN_DEMO_URL || 'http://127.0.0.1:6390/demo/';
(async () => {
 const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_EXECUTABLE || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
 const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
 const errors = [], failed = [], external = [], checks = [];
 page.on('pageerror', error => errors.push(String(error)));
 page.on('requestfailed', req => failed.push({ url: req.url(), reason: req.failure()?.errorText }));
 page.on('request', req => { if (!req.url().startsWith(new URL(base).origin) && !req.url().startsWith('data:')) external.push(req.url()); });
 const state = async () => JSON.parse(await page.locator('#state').textContent());
 const click = async (action, suffix='') => page.locator(`[data-action="${action}"]${suffix}`).click();
 const screenshot = async name => { await page.evaluate(async()=>{await Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{})));window.scrollTo(0,0);});await page.screenshot({ path: path.join(root, `preview-${name}.png`) }); };
 const contains = async (selector, text) => assert.ok((await page.locator(selector).innerText()).includes(text), text);
 try {
  await page.goto(base);
  await page.getByRole('tab', { name: '派对', exact: true }).waitFor();
  assert.deepEqual(await page.getByRole('tab').allTextContents(), ['派对', 'KTV', '玩法']);
  assert.equal(await page.locator('#room-name').getAttribute('maxlength'), '15');
  await page.locator('[data-scenario="gameTab"]').check();
  assert.deepEqual(await page.getByRole('tab').allTextContents(), ['派对', '开黑', 'KTV', '玩法']);
  checks.push('Tab ordering, remote game-tab scenario, 15-unit input limit');
  await page.getByRole('tab', { name: '玩法', exact: true }).click();
  await click('createMode', '[data-key="mode:18"]');
  assert.equal(await page.locator('.create-mode-grid').count(), 1);
  await screenshot('create-rn');
  await page.locator('[data-scenario="creationBranch"]').selectOption('native');
  assert.equal(await page.locator('.mode-strip').count(), 1);
  await screenshot('create-native');
  await page.locator('[data-scenario="creationBranch"]').selectOption('rn');
  await click('openType');
  await click('selectType', '[data-value="4"]');
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal((await state()).classify, 4);
  checks.push('RN five-column and Native horizontal mode selection; type selection immediately closes');
  await click('openPrivacy');
  await contains('#overlay', '仅挚友可进');
  await click('selectStatus', '[data-value="2"]');
  assert.equal((await state()).privateStatus, 2);
  assert.equal(await page.getByRole('dialog').count(), 0);
  await click('openPrivacy');await page.keyboard.press('Escape');
  assert.equal((await state()).privateStatus, 2);
  checks.push('RN status picker immediately commits and closes; Escape does not submit');
  await screenshot('create');
  await page.getByRole('tab', { name: 'KTV', exact: true }).click();
  assert.equal((await state()).privateStatus,0);
  await page.locator('#room-name').fill('派对交互研究');
  await page.locator('[data-scenario="createFailure"]').check();
  await click('create');
  await page.getByRole('alert').filter({hasText:'模拟创建失败'}).waitFor();
  assert.equal((await state()).screen, 'create');
  await page.locator('[data-scenario="createFailure"]').uncheck();
  await click('create');
  await page.locator('[data-action="settings"]').waitFor();
  assert.equal((await state()).screen, 'room');
  checks.push('Creation response failure retains form, retry enters offline room');
  await click('settings');
  await contains('#overlay', '当前玩法:KTV');
  await screenshot('settings');
  await page.locator('#overlay [data-action="plays"]').click();
  await contains('#overlay', '更多玩法');
  await page.locator('#play-filter').selectOption('音乐');
  await contains('#overlay', 'KTV');
  await page.locator('#play-filter').selectOption('全部玩法');
  await screenshot('plays');
  await click('play', '[data-key="mode:2"]');
  await contains('#overlay', '确定切换为【欢乐PK】');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  assert.equal((await state()).primary.id, 1);
  await click('play', '[data-key="mode:2"]');
  await page.getByRole('button', { name: '立即切换', exact: true }).click();
  assert.equal((await state()).primary.id, 2);
  checks.push('Room settings → category picker → cancel/success conflict switching');
  await click('settings');await page.locator('#overlay [data-action="plays"]').click();
  await click('secondary');
  await contains('#overlay','二级分组');
  await click('play', '[data-key="feature:500002"]');
  assert.equal((await state()).primary.id, 2);
  assert.ok((await state()).features.includes('feature:500002'));
  checks.push('Secondary function selection preserves primary mode');
  await page.locator('[data-scenario="role"]').selectOption('3');
  await click('settings');
  assert.equal(await page.locator('.current-card').count(), 0);
  await contains('#overlay', '用户管理');
  await page.keyboard.press('Escape');
  checks.push('Manager role hides owner-only current-play card');
  for (const width of [390,320]) {
   await page.setViewportSize({ width, height: 900 });
   assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `${width}px horizontal overflow`);
   await click('settings');
   const bounds = await page.getByRole('dialog').boundingBox();
   assert.ok(bounds.x >= -1 && bounds.x+bounds.width <= width+1, `${width}px dialog overflow`);
   await screenshot(`mobile-${width}`);
   await page.keyboard.press('Escape');
  }
  checks.push('390px and 320px layouts and dialogs fit viewport');
  await page.emulateMedia({ reducedMotion:'reduce' });
  await page.setViewportSize({width:1440,height:1050});
  for (const url of ['../REPORT.md','../analysis/rn/STATUS-FINDINGS.md','../analysis/rn/CREATE-RN-FINDINGS.md']) {
   const response=await page.request.get(new URL(url,base).href);assert.equal(response.status(),200);
  }
  checks.push('Report links resolve; reduced-motion media accepted');
  assert.deepEqual(errors, []);assert.deepEqual(failed, []);assert.deepEqual(external, []);
  const unitTests=JSON.parse(await fs.readFile(path.join(root,'verification/unit-summary.json'),'utf8'));
  const result={status:'passed',unit_tests:unitTests,checked_at_utc:new Date().toISOString(),browser:await browser.version(),checks,page_errors:errors,failed_requests:failed,external_requests:external,original_android_app_executed:false,live_business_api_called:false,scope:'Only offline reconstruction browser behavior; does not verify Soul runtime, backend, audio, multiplayer, or pixel equivalence'};
  await fs.writeFile(path.join(root,'verification.json'),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result,null,2));
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
